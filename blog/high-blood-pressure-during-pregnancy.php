<h2 id="what-counts">What Counts as High Blood Pressure in Pregnancy?</h2>
<p>A blood pressure reading has two numbers. The top one (systolic) is the pressure when your heart beats; the bottom one (diastolic) is the pressure between beats. In pregnancy, doctors use these thresholds:</p>
<div class="dabg-table">
<table>
    <thead><tr><th>Reading (mmHg)</th><th>What It Means</th></tr></thead>
    <tbody>
        <tr><td>Below 120/80</td><td>Normal</td></tr>
        <tr><td>120 to 139 / 80 to 89</td><td>Upper normal; watch closely, especially if rising from your early readings</td></tr>
        <tr><td>140/90 or higher</td><td>High blood pressure; needs confirmation and assessment</td></tr>
        <tr><td>160/110 or higher</td><td>Severe range; needs urgent treatment the same day</td></tr>
    </tbody>
</table>
</div>
<p>One high reading is not a diagnosis. Anxiety, a rushed walk into the clinic or the wrong cuff size can all push numbers up. That is why the reading is repeated after rest, and why a diagnosis needs two high readings at least four hours apart. A single reading of 160/110 or above is different: it is treated as urgent straight away.</p>

<h2 id="types">The Four Types of Pregnancy Hypertension</h2>
<p>Not all high BP in pregnancy is the same, and the type decides how you are managed.</p>
<ul>
    <li><strong>Chronic hypertension:</strong> high BP that was present before pregnancy or is found before 20 weeks. Many women only discover it at their first antenatal visit.</li>
    <li><strong>Gestational hypertension:</strong> new high BP after 20 weeks, with no protein in the urine and no signs of organ strain. It usually settles after delivery, but around a quarter of women with it go on to develop preeclampsia, so it is watched closely.</li>
    <li><strong>Preeclampsia:</strong> new high BP after 20 weeks along with protein in the urine or signs that organs such as the kidneys, liver, brain or placenta are under strain.</li>
    <li><strong>Chronic hypertension with superimposed preeclampsia:</strong> preeclampsia developing in a woman who already had high BP.</li>
</ul>

<h2 id="preeclampsia">What Is Preeclampsia?</h2>
<p>Preeclampsia is a condition that starts in the placenta. For reasons that are still being studied, the blood vessels supplying the placenta do not develop properly early in pregnancy. The struggling placenta then releases substances into the mother's blood that damage the lining of blood vessels throughout her body. High blood pressure is the visible sign, but the real problem is that many organs can be affected at once.</p>
<p>It can progress to serious complications:</p>
<ul>
    <li><strong>Eclampsia:</strong> seizures in a woman with preeclampsia, a medical emergency.</li>
    <li><strong>HELLP syndrome:</strong> breakdown of red blood cells, raised liver enzymes and a low platelet count. It can develop quickly, sometimes with only moderately raised BP.</li>
    <li><strong>Placental abruption:</strong> the placenta separating from the uterine wall before delivery, causing bleeding and pain.</li>
    <li><strong>Stroke, kidney injury or fluid on the lungs</strong> in severe, untreated cases.</li>
</ul>
<p>The important point is that it can go from mild to severe within days. That is why the monitoring is frequent and why symptoms should never be left until the next appointment.</p>

<h2 id="symptoms">Symptoms That Need Urgent Attention</h2>
<p>Many women with preeclampsia feel completely well, which is exactly why BP and urine checks happen at every visit. When symptoms do appear, these are the ones to act on the same day:</p>
<ul>
    <li>A severe headache that does not ease with rest or paracetamol</li>
    <li>Blurred vision, flashing lights, spots or sensitivity to light</li>
    <li>Pain just below the ribs on the right side, or in the upper middle abdomen</li>
    <li>Sudden swelling of the face, hands or feet, especially if it appears over a day or two</li>
    <li>Nausea or vomiting in the second half of pregnancy</li>
    <li>Breathlessness, particularly when lying flat</li>
    <li>Passing much less urine than usual</li>
    <li>Reduced baby movements</li>
</ul>
<p>A seizure, confusion or a severe headache with visual changes means going to hospital immediately. Our guide to <a href="../blog/warning-signs-of-high-risk-pregnancy.php" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">warning signs of a high-risk pregnancy</a> covers the other symptoms that should never wait.</p>

