<h2 id="faqs">Frequently Asked Questions</h2>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">1. What blood pressure is too high during pregnancy?</h3>
    <p>A reading of 140/90 mmHg or higher on two occasions at least four hours apart is considered high. A reading of 160/110 or higher is in the severe range and needs treatment the same day.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">2. What is the difference between gestational hypertension and preeclampsia?</h3>
    <p>Both involve new high blood pressure after 20 weeks. Gestational hypertension has no protein in the urine and no organ involvement. Preeclampsia also shows protein in the urine or signs of strain on the kidneys, liver, brain, blood or placenta, and needs closer monitoring.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">3. Can preeclampsia happen without symptoms?</h3>
    <p>Yes, often. Many women feel completely well until the condition is advanced. This is why blood pressure and urine protein are checked at every antenatal visit, even when you have no complaints.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">4. Is it safe to take BP medicines in pregnancy?</h3>
    <p>Yes, when they are chosen for pregnancy. Labetalol, nifedipine and methyldopa are widely used and considered safe. Some common BP medicines are not safe for the baby, so only take what your obstetrician prescribes.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">5. Will I need a caesarean if I have preeclampsia?</h3>
    <p>Not necessarily. Many women with preeclampsia have an induced normal delivery. A caesarean is advised when the condition is severe and labour is not a safe or quick option, or for the usual obstetric reasons.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">6. Does preeclampsia go away after delivery?</h3>
    <p>It usually settles within days to weeks after the placenta is delivered, but it can appear or worsen in the first six weeks after birth. Continue checking your BP at home and report any severe headache or breathlessness straight away.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">7. Can preeclampsia happen again in my next pregnancy?</h3>
    <p>The risk is higher after a previous episode, especially if it was severe or early. Low-dose aspirin from 12 to 16 weeks, calcium supplementation and early antenatal care reduce the risk in a future pregnancy.</p>
</div>
