<p>For the baby, the main concern is the placenta. Reduced blood flow can slow growth, reduce the amniotic fluid and, if the condition becomes severe, make an early delivery necessary. That is why growth scans and Doppler studies are part of the monitoring.</p>
<p>For the mother, the risks above are the reason for close watching. There is also a longer-term point that is often missed: women who had preeclampsia have a higher lifetime risk of high blood pressure and heart disease. An annual BP check after delivery is worth continuing for life.</p>

<h2 id="home-bp">Checking Your Blood Pressure at Home Correctly</h2>
<p>If you have been diagnosed with high BP, you may be asked to check it at home between visits. A reading is only useful if it is taken properly:</p>
<ul>
    <li>Use an automatic upper-arm monitor, not a wrist monitor</li>
    <li>Check the cuff fits your arm; a cuff that is too small gives falsely high numbers</li>
    <li>Sit quietly for five minutes first, back supported, feet flat, legs uncrossed</li>
    <li>Rest your arm on a table so the cuff is at heart level</li>
    <li>Do not talk or check your phone during the reading</li>
    <li>Take two readings a minute apart and write both down with the date and time</li>
</ul>
<p>Agree in advance with your doctor what number should make you call. A common rule is to phone the same day for any reading of 140/90 or above, and to go to hospital for 160/110 or above or for any reading accompanied by symptoms.</p>

<h2 id="treatment">Treatment and Delivery Timing</h2>
<h3>Medicines</h3>
<p>Several blood pressure medicines are safe in pregnancy. Labetalol, nifedipine and methyldopa are the ones most commonly used in India. Some BP medicines used outside pregnancy, such as ACE inhibitors, are not safe for the baby, so never continue or start a BP medicine without your obstetrician's advice.</p>
<h3>Monitoring</h3>
<p>Depending on severity, this means BP checks once or twice a week or more, urine protein testing, blood tests for platelets, liver and kidney function, and growth scans with Doppler studies for the baby.</p>
<h3>Protecting against seizures</h3>
<p>In severe preeclampsia, magnesium sulphate is given in hospital to prevent eclampsia. It is one of the most effective and well-established treatments in obstetrics.</p>
<h3>Delivery: the only cure</h3>
<p>Medicines control blood pressure, but only delivering the placenta cures preeclampsia. The timing is a balance between the mother's safety and the baby's maturity:</p>
<div class="dabg-table">
<table>
    <thead><tr><th>Situation</th><th>Usual Approach</th></tr></thead>
    <tbody>
        <tr><td>Gestational hypertension or preeclampsia without severe features</td><td>Close monitoring, with delivery usually advised around 37 weeks</td></tr>
        <tr><td>Severe preeclampsia after 34 weeks</td><td>Stabilise the mother, then deliver</td></tr>
        <tr><td>Severe preeclampsia before 34 weeks</td><td>Steroid injections to mature the baby's lungs, careful inpatient monitoring, delivery if the mother's or baby's condition worsens</td></tr>
        <tr><td>Eclampsia or HELLP syndrome</td><td>Stabilise and deliver, whatever the gestation</td></tr>
    </tbody>
</table>
</div>
<p>High BP does not automatically mean a caesarean. Many women with well-controlled hypertension have an induced normal delivery.</p>
<h3>After delivery</h3>
<p>Preeclampsia can appear or worsen in the first six weeks after birth, most often in the first few days. Keep checking your BP after going home, and report a severe headache or breathlessness straight away.</p>

<h2 id="prevention">Can Preeclampsia Be Prevented?</h2>
<p>It cannot always be prevented, but the risk can be lowered:</p>
<ul>
    <li><strong>Low-dose aspirin:</strong> for women at high risk, started ideally between 12 and 16 weeks and continued until about 36 weeks. Only take it on prescription, at the dose your doctor gives.</li>
    <li><strong>Calcium supplementation:</strong> reduces the risk where dietary calcium is low, which is common in India. Calcium tablets are provided from the second trimester under the national antenatal programme.</li>
    <li><strong>Reaching a healthy weight before pregnancy</strong> and staying active during it.</li>
    <li><strong>Controlling existing BP or diabetes</strong> before you conceive.</li>
    <li><strong>Never missing an antenatal BP check</strong>, even when you feel fine.</li>
</ul>

