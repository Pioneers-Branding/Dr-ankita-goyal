<h2 id="what-is-pcos">What is PCOS and How Common Is It?</h2>
<p>PCOS stands for Polycystic Ovary Syndrome. In a normal cycle, one egg matures each month and is released. In PCOS, hormonal imbalance stops that egg from being released. The follicle stays in the ovary as a small fluid-filled sac, and over months these accumulate, giving the ovary its characteristic appearance on ultrasound.</p>
<p>Two things drive it. First, higher-than-normal levels of male hormones (androgens), which cause acne, facial hair and hair fall. Second, <strong>insulin resistance</strong>, where the body produces plenty of insulin but cells respond poorly to it. That is why weight gain around the abdomen is so common, and why PCOS is as much a metabolic condition as a gynaecological one.</p>
<p>Studies across India suggest somewhere between 1 in 5 and 1 in 10 women of reproductive age are affected. It is one of the most common reasons women visit a gynecologist, and one of the most commonly missed for years because irregular periods get dismissed as normal.</p>

<h2 id="pcos-vs-pcod">PCOS vs PCOD: The Real Difference</h2>
<p>Patients use these terms interchangeably, and even many clinics do. They are related but not identical.</p>
