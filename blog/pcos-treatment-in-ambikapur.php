<h2 id="faqs">Frequently Asked Questions</h2>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">1. Can PCOS be cured permanently?</h3>
    <p>PCOS is managed rather than cured. However, symptoms can be brought under complete control, cycles can become regular, and pregnancy is very achievable. Many women live symptom-free for years through weight and insulin management alone.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">2. Can PCOS be treated without surgery?</h3>
    <p>Yes. The overwhelming majority of cases need no surgery at all. Weight control, diet, exercise and medication manage most patients. Laparoscopic ovarian drilling is considered only when medication has failed.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">3. Can I get pregnant naturally with PCOS?</h3>
    <p>Many women do. PCOS interferes with ovulation, not with the ability to carry a pregnancy. Weight optimisation alone restores natural ovulation in a significant number of women, and ovulation induction tablets help most of the rest.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">4. Does PCOS go away after marriage or after having a baby?</h3>
    <p>No. This is a persistent myth. Marriage has no effect whatsoever. Symptoms sometimes ease after pregnancy because of weight and hormonal shifts, but the underlying condition remains and needs continued attention.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">5. Will I need to take medicines for life?</h3>
    <p>Not necessarily. Medication is often used for a defined period to regulate cycles or achieve pregnancy. Where lifestyle change is sustained, many women reduce or stop medication under supervision.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">6. Is PCOS dangerous if left untreated?</h3>
    <p>Untreated PCOS raises the long-term risk of type 2 diabetes, high blood pressure, cholesterol problems and changes to the uterine lining from years of missed periods. None of these are immediate emergencies, which is exactly why the condition gets ignored for too long.</p>
