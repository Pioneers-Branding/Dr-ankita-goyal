<p>In short: PCOD is largely an ovarian problem, while PCOS affects metabolism, weight, skin, hair and long-term health alongside the ovaries. The tests are the same, but the follow-up is more thorough for PCOS.</p>

<h2 id="symptoms">9 Symptoms You Should Not Ignore</h2>
<p>You do not need all nine. Two or three appearing together is enough reason to get assessed:</p>
<ul>
    <li><strong>Irregular or missed periods:</strong> cycles longer than 35 days, or fewer than eight periods a year.</li>
    <li><strong>Heavy or unpredictable bleeding:</strong> when a period finally arrives after a long gap, the lining has built up and bleeding can be heavy.</li>
    <li><strong>Weight gain around the abdomen:</strong> especially when eating habits have not changed.</li>
    <li><strong>Excess facial or body hair (hirsutism):</strong> on the chin, upper lip, chest or abdomen.</li>
    <li><strong>Hair thinning on the scalp:</strong> a widening parting or reduced volume.</li>
    <li><strong>Persistent acne:</strong> particularly along the jawline, continuing well past the teenage years.</li>
    <li><strong>Dark velvety patches of skin:</strong> on the neck, underarms or groin, a visible marker of insulin resistance.</li>
    <li><strong>Difficulty conceiving:</strong> after a year of trying, or six months if you are over 35.</li>
    <li><strong>Mood changes and fatigue:</strong> low mood, anxiety and tiredness are genuinely part of the picture, not imagined.</li>
</ul>

<h2 id="diagnosis">How PCOS is Diagnosed</h2>
<p>Diagnosis follows the Rotterdam criteria: you need <strong>two out of three</strong> features present. Irregular or absent ovulation; clinical or blood-test evidence of high androgens; and polycystic ovaries on ultrasound. Importantly, cysts alone do not equal PCOS, and you can have PCOS with completely normal-looking ovaries.</p>
