<h2 id="faqs">Frequently Asked Questions</h2>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">1. How long should we try before seeing a doctor?</h3>
    <p>Twelve months of regular unprotected intercourse, or six months if the woman is over 35 and three months if she is over 38. Go sooner if periods are irregular, or if either partner has a known reproductive problem.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">2. Should my husband be tested too?</h3>
    <p>Yes, and at the same time, not afterwards. A male factor is involved in roughly half of all cases. A semen analysis is inexpensive and non-invasive, and it should be among the first tests done.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">3. What tests are done first?</h3>
    <p>For the woman: hormone profile including AMH, pelvic ultrasound, ovulation tracking and a tubal test. For the man: semen analysis. These usually identify the problem within one cycle.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">4. Can PCOS be treated so I can conceive?</h3>
    <p>Yes. PCOS interferes with ovulation, and ovulation can usually be induced. Weight optimisation alone restores natural cycles in many women, and letrozole or clomiphene tablets help most of the rest.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">5. Do we need IVF?</h3>
    <p>Most couples do not. IVF is genuinely indicated for blocked tubes, severe male factor, significantly reduced ovarian reserve, severe endometriosis or failure of earlier treatment. If it is suggested before basic tests are complete, seek a second opinion.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">6. What is the difference between IUI and IVF?</h3>
    <p>In IUI, washed sperm is placed into the uterus at ovulation and fertilisation happens inside the body, requiring at least one open tube. In IVF, eggs are collected and fertilised in the laboratory and an embryo is transferred. IVF is more invasive and more expensive.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">7. How often should we have intercourse?</h3>
    <p>Every two to three days throughout the cycle. This covers the fertile window without the stress of precise timing, and it keeps sperm quality good. Rigid scheduling around ovulation kits adds pressure for little benefit.</p>
</div>
