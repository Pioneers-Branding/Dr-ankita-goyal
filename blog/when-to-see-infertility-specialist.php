<h2 id="myths">Myths That Cause Real Harm</h2>
<ul>
    <li><strong>It is the woman's problem.</strong> A male factor is involved in roughly half of cases. Testing only the woman wastes months.</li>
    <li><strong>Lying with legs raised afterwards helps.</strong> It does not. Sperm reach the tubes within minutes.</li>
    <li><strong>Stress alone causes infertility.</strong> Severe stress can disturb cycles, but it is rarely the sole cause, and blaming it delays diagnosis.</li>
    <li><strong>IVF is the only option after a year of trying.</strong> Most couples conceive with far simpler treatment.</li>
    <li><strong>One abnormal semen report is final.</strong> Counts fluctuate. Always repeat before concluding anything.</li>
    <li><strong>Age only matters after 40.</strong> Fertility declines measurably from the early thirties and faster after 37.</li>
</ul>

