<h2 id="when-to-go">When Is It Time to Get Tested?</h2>
<p>Among couples with no fertility problem, roughly 8 in 10 conceive within a year of regular trying. So a year is the point at which investigation becomes sensible rather than premature.</p>
<p>Do not wait the full year if any of these apply:</p>
<ul>
    <li>The woman is over 35; investigate at six months</li>
    <li>The woman is over 38; investigate at three months</li>
    <li>Periods are irregular, very infrequent or absent</li>
    <li>Known <a href="../blog/pcos-treatment-in-ambikapur" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">PCOS</a>, <a href="../blog/endometriosis-period-pain" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">endometriosis</a> or <a href="../blog/fibroid-treatment-in-ambikapur" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">fibroids</a></li>
    <li>Previous pelvic surgery, ectopic pregnancy or pelvic infection</li>
    <li>Two or more miscarriages</li>
    <li>The man has had an undescended testis, testicular injury, surgery or mumps after puberty</li>
    <li>Either partner has had cancer treatment</li>
</ul>
<p>Age is the one factor that cannot be recovered later. Egg quantity and quality decline steadily through the thirties and more sharply after 37. Waiting another year to avoid an awkward conversation is the most expensive delay in fertility care.</p>

<h2 id="causes">What Actually Causes Infertility</h2>
<p>A useful rough split: about a third of cases are due to a female factor, about a third to a male factor, and the remainder are combined or unexplained. That makes testing the man first and early both cheaper and faster than it is usually treated as.</p>
