<p>Genital tuberculosis deserves specific mention in India. It can silently damage the tubes and the uterine lining with no obvious symptoms, and it is a recognised cause of tubal infertility here in a way it is not in many other countries.</p>

<h2 id="tests-women">Tests for the Woman</h2>
<ul>
    <li><strong>Hormone profile:</strong> FSH, LH, TSH, prolactin and AMH, which indicates ovarian reserve</li>
    <li><strong>Pelvic ultrasound:</strong> uterus, lining, ovaries and antral follicle count</li>
    <li><strong>Ovulation tracking:</strong> serial scans across a cycle to confirm an egg is actually released</li>
    <li><strong>Tubal testing:</strong> HSG, an X-ray with dye, or SSG using ultrasound, to check the tubes are open</li>
    <li><strong>Diagnostic laparoscopy and hysteroscopy:</strong> a direct look at the pelvis and uterine cavity, used when earlier tests are unclear or endometriosis is suspected. It can diagnose and treat in the same sitting</li>
    <li><strong>General screening:</strong> haemoglobin, blood sugar, vitamin D, and sickle cell where relevant</li>
</ul>

<h2 id="tests-men">Tests for the Man</h2>
<p>The first test is a semen analysis. It is inexpensive, non-invasive and gives a large share of the answer, which is exactly why it should be done at the very start rather than after months of investigating the woman.</p>
<p>It is done after two to five days of abstinence, and an abnormal result is repeated after a few weeks, because counts vary with illness, fever and stress. If abnormalities persist, further tests include hormone levels, a scrotal ultrasound for varicocele, and in selected cases genetic testing.</p>
<p>A varicocele, which is a collection of enlarged veins in the scrotum, is one of the more commonly correctable causes of male infertility.</p>

<h2 id="treatment">Treatment, Step by Step</h2>
<p>Treatment follows a ladder. Most couples succeed on the lower rungs.</p>
<ul>
    <li><strong>Step 1: Timing and lifestyle.</strong> Intercourse every two to three days through the cycle covers the fertile window without the stress of precise timing. Weight optimisation alone restores ovulation in many women with PCOS.</li>
    <li><strong>Step 2: Ovulation induction.</strong> Letrozole or clomiphene tablets stimulate the ovary to release an egg, with scans to track follicle growth. This is the single most effective treatment for PCOS-related infertility.</li>
    <li><strong>Step 3: Correcting a specific problem.</strong> Removing a submucosal fibroid or polyp, treating endometriosis, correcting thyroid or prolactin abnormalities, or repairing a varicocele.</li>
    <li><strong>Step 4: IUI.</strong> Washed, concentrated sperm placed directly into the uterus at ovulation. Suitable for mild male factor, unexplained infertility or cervical factors, with at least one open tube.</li>
    <li><strong>Step 5: IVF or ICSI.</strong> Eggs fertilised outside the body and an embryo transferred. Necessary for blocked tubes, severe male factor, advanced age or repeated failure of earlier steps.</li>
</ul>
<p>Each step is usually tried for a defined number of cycles, commonly three to six, before moving up. Open-ended repetition of a treatment that is not working wastes both money and fertile years.</p>

<h2 id="ivf">When IVF Is Genuinely the Right Step</h2>
<p>IVF is a remarkable treatment and is over-recommended in India. It is genuinely indicated for both tubes blocked, severe male factor requiring ICSI, significantly reduced ovarian reserve with age pressure, severe endometriosis, and failure of three to six properly conducted IUI cycles.</p>
<p>It is premature if the basic tests have not been completed, if ovulation induction has not been tried where it is appropriate, or if a correctable problem such as a polyp or thyroid disorder has not been addressed.</p>
<p>If IVF is recommended at a first consultation before a semen analysis and tubal test have been done, that is a reasonable moment to seek a second opinion.</p>

