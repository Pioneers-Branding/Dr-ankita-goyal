<p>The trick is combining them. Iron from plant foods is absorbed much better when eaten with vitamin C, so squeeze lemon on your dal or sabzi, or eat a guava or amla with the meal. Cooking in an iron kadhai adds a small amount of iron to food. And move the after-meal cup of tea to at least an hour later.</p>

