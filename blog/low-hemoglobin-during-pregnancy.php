<h2 id="faqs">Frequently Asked Questions</h2>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">1. What is the normal hemoglobin level in pregnancy?</h3>
    <p>11 g/dL or above is normal in pregnancy. Between 10 and 10.9 is mild anaemia, 7 to 9.9 is moderate, and below 7 is severe. A small fall is expected as blood volume rises, but below 11 needs treatment.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">2. How quickly can hemoglobin be increased in pregnancy?</h3>
    <p>With iron tablets taken correctly, hemoglobin typically rises by about 1 g/dL every two to three weeks. IV iron works faster, often showing a clear rise within two to three weeks. A blood transfusion raises it immediately but is kept for severe cases.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">3. Is IV iron safe during pregnancy?</h3>
    <p>Yes, in the second and third trimesters, when given in a hospital setting with monitoring. It is used for moderate or severe anaemia, or when tablets are not tolerated or not working. It is generally avoided in the first trimester.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">4. Can low hemoglobin harm my baby?</h3>
    <p>Moderate or severe anaemia raises the risk of preterm birth and low birth weight, and the baby may start life with lower iron stores. Mild anaemia that is treated promptly rarely causes problems for the baby.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">5. Why is my hemoglobin not increasing despite iron tablets?</h3>
    <p>Common reasons are taking the tablet with tea or milk, missing doses because of side effects, worm infestation, B12 or folate deficiency, or an inherited condition such as thalassaemia trait or sickle cell. Tests like ferritin and hemoglobin electrophoresis identify the cause.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">6. Should I be tested for sickle cell in pregnancy?</h3>
    <p>In Chhattisgarh, yes. The state has one of the highest burdens of the sickle cell gene in India. Screening is a simple blood test, and if you carry the trait, testing your partner tells you whether the baby could be affected.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">7. Which foods increase hemoglobin fastest?</h3>
    <p>Green leafy vegetables such as chaulai and drumstick leaves, ragi and other millets, pulses, eggs, fish and meat. Eat them with vitamin C foods such as amla, lemon or guava, and keep tea away from meals. Diet supports treatment but rarely corrects pregnancy anaemia alone.</p>
</div>
