        <dt>At delivery</dt><dd>Normal blood loss becomes more dangerous; a higher chance of needing a transfusion</dd>
        <dt>For the baby</dt><dd>Higher risk of preterm birth and low birth weight</dd>
        <dt>After birth</dt><dd>Slower recovery, difficulty breastfeeding, and the baby starts life with lower iron stores</dd>
