<h2 id="what-is-normal">What Hemoglobin Level Is Normal in Pregnancy?</h2>
<p>Hemoglobin is the protein in red blood cells that carries oxygen. In pregnancy it is measured in grams per decilitre (g/dL), and the World Health Organization thresholds used in India are:</p>
<div class="dabg-table">
<table>
    <thead><tr><th>Hemoglobin (g/dL)</th><th>Category</th><th>What Usually Happens</th></tr></thead>
    <tbody>
        <tr><td>11 or above</td><td>Normal</td><td>Routine iron and folic acid supplements</td></tr>
        <tr><td>10 to 10.9</td><td>Mild anaemia</td><td>Treatment dose of oral iron, diet review, repeat test in about four weeks</td></tr>
        <tr><td>7 to 9.9</td><td>Moderate anaemia</td><td>Tests for the cause; IV iron often advised, especially in the second half of pregnancy</td></tr>
        <tr><td>Below 7</td><td>Severe anaemia</td><td>Urgent assessment, usually in hospital; IV iron or blood transfusion depending on timing</td></tr>
    </tbody>
</table>
</div>
<p>A slight fall in hemoglobin during pregnancy is expected. Your blood volume rises by nearly half, and the fluid part rises faster than the red cells, which dilutes the blood. That is why the cut-off is lower in pregnancy than for other women. A result below 11 g/dL, however, is more than dilution and deserves attention.</p>

<h2 id="why-it-drops">Why Hemoglobin Drops During Pregnancy</h2>
<p>A pregnant woman needs roughly two to three times as much iron as she did before, mainly in the second and third trimesters when the baby builds its own iron stores. Many women start pregnancy with low reserves, so the gap opens quickly. The common causes:</p>
<ul>
    <li><strong>Iron deficiency:</strong> by far the most common cause, from low reserves before pregnancy plus the extra demand.</li>
    <li><strong>Folic acid or vitamin B12 deficiency:</strong> B12 deficiency is particularly common in vegetarian diets.</li>
    <li><strong>Heavy periods before pregnancy:</strong> from conditions such as <a href="../blog/fibroid-treatment-in-ambikapur.php" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">fibroids</a>, which drain iron stores for years.</li>
    <li><strong>Closely spaced pregnancies:</strong> less than 18 months between deliveries leaves little time to rebuild iron.</li>
    <li><strong>Worm infestation:</strong> hookworm causes slow blood loss from the gut, which is why deworming is part of antenatal care.</li>
    <li><strong>Malaria:</strong> destroys red blood cells and remains a concern in parts of Chhattisgarh.</li>
    <li><strong>Inherited blood conditions:</strong> sickle cell disease and thalassaemia, covered below.</li>
    <li><strong>Twins or triplets:</strong> higher demand for iron.</li>
</ul>

<h2 id="symptoms">Symptoms of Low Hemoglobin</h2>
<p>Mild anaemia often causes no symptoms at all, which is why it is picked up on blood tests rather than by how you feel. As it worsens, you may notice:</p>
<ul>
    <li>Tiredness beyond the normal fatigue of pregnancy</li>
    <li>Breathlessness when climbing stairs or walking briskly</li>
    <li>Pale skin, pale inner eyelids, pale nails or tongue</li>
    <li>Dizziness or feeling faint, especially when standing up</li>
    <li>A racing or pounding heartbeat</li>
    <li>Headaches and difficulty concentrating</li>
    <li>Cold hands and feet</li>
    <li>Craving to eat non-food items such as mud, chalk, ice or raw rice, a sign called pica</li>
</ul>
<p>Breathlessness at rest, chest pain or fainting means you should be seen urgently rather than waiting for your next visit.</p>

