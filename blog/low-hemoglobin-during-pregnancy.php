<p>The practical message is timing. Hemoglobin rises slowly, by roughly 1 g/dL every two to three weeks on effective treatment. Anaemia found at 34 weeks leaves very little time to correct it before delivery, which is why testing early and repeating it matters.</p>

<h2 id="tests">Tests That Find the Real Cause</h2>
<p>Treating every low hemoglobin with iron tablets works for most women, but not all. If the number does not rise, the cause needs to be found. A <a href="https://www.google.com/maps/place/?cid=12404751412948847125" target="_blank" rel="noopener" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">low hemoglobin during pregnancy doctor</a> will usually check:</p>
<ul>
    <li><strong>Complete blood count with red cell indices:</strong> small pale cells point to iron deficiency or thalassaemia; large cells point to folate or B12 deficiency.</li>
    <li><strong>Serum ferritin:</strong> the best single measure of iron stores.</li>
    <li><strong>Peripheral smear:</strong> a look at the red cells under the microscope.</li>
    <li><strong>Sickle cell test and hemoglobin electrophoresis (HPLC):</strong> to detect sickle cell or thalassaemia trait.</li>
    <li><strong>Vitamin B12 and folate levels:</strong> where cells are large or diet is vegetarian.</li>
    <li><strong>Stool examination and malaria test:</strong> when history suggests them.</li>
</ul>

<h2 id="sickle-cell">Sickle Cell and Thalassaemia in Chhattisgarh</h2>
<p>This is the part of anaemia care that is most specific to Chhattisgarh. The state carries one of the highest burdens of the sickle cell gene in India, particularly in some communities, and it is a focus of the national Sickle Cell Anaemia Elimination Mission. Thalassaemia trait is also seen across the region.</p>
<p>This matters in pregnancy for three reasons:</p>
<ul>
    <li><strong>Iron may not be the answer.</strong> A woman with thalassaemia trait can have a low hemoglobin with normal iron stores. Giving her extra iron for months does not help, and in some blood conditions can cause iron to build up.</li>
    <li><strong>Sickle cell disease makes pregnancy high-risk.</strong> Women with the disease have more pain crises, infections, preeclampsia and preterm birth, and need specialist monitoring throughout.</li>
    <li><strong>The baby can inherit it.</strong> If both parents carry the trait, each pregnancy has a one in four chance of the baby having sickle cell disease. Testing the partner, ideally early in pregnancy, gives the couple time to understand their options.</li>
</ul>
<p>If you or your family have ever been told about sickle cell, or if your hemoglobin does not rise on iron, ask for screening. It is a simple blood test.</p>

<h2 id="treatment">Treatment: Tablets, IV Iron and Transfusion</h2>
<h3>Iron and folic acid tablets</h3>
<p>Under India's Anaemia Mukt Bharat programme, every pregnant woman is advised to take one iron and folic acid tablet daily from the second trimester for at least 180 days, continuing for six months after delivery. Women who are already anaemic are given a higher treatment dose. To get the most from them:</p>
<ul>
    <li>Take them on an empty stomach or between meals, with water or lemon water</li>
    <li>Keep tea, coffee and milk at least an hour away from the tablet; they block absorption</li>
    <li>Take calcium tablets at a different time of day, at least two hours apart</li>
    <li>Constipation and black stools are common and harmless; more water, fibre and fruit help</li>
    <li>If tablets make you sick, tell your doctor rather than stopping; a different preparation or timing usually solves it</li>
</ul>
<h3>IV iron</h3>
<p>For moderate or severe anaemia in the second or third trimester, or when tablets are not tolerated or not working, iron can be given through a drip. Ferric carboxymaltose, the most commonly used form, can replace a large amount of iron in one or two short sessions and raises hemoglobin faster than tablets. It is given in a hospital setting with monitoring. It is generally avoided in the first trimester.</p>
<h3>Blood transfusion</h3>
<p>Reserved for severe anaemia, particularly close to delivery when there is no time for iron to work, or when there is heavy bleeding. It works immediately but carries its own risks, so the aim of early testing is to avoid ever needing it.</p>
<h3>Treating the cause</h3>
<p>Deworming tablets in the second trimester, vitamin B12 or folic acid where deficient, malaria treatment if present, and specialist care for sickle cell disease.</p>

