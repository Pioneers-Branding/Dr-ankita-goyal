      <h2 id="pcos">PCOS, irregular periods and the symptoms women delay too long</h2>

      <h3>Can PCOS be treated without surgery?</h3>
      <p>Yes &mdash; in most cases. PCOS is a hormonal and metabolic condition, so the foundation of treatment is lifestyle: losing even 5&ndash;10% of body weight can restore ovulation on its own. Medicines are added to regularise cycles, improve insulin sensitivity, or induce ovulation when a woman is trying to conceive. Laparoscopic ovarian drilling is reserved for the small group who do not respond to medical treatment.</p>

      <h3>What causes irregular periods after 30?</h3>
      <p>The usual causes are PCOS, thyroid disorders, anaemia, fibroids or polyps, sudden weight change, and stress. After 40, perimenopause enters the picture. A pelvic ultrasound along with thyroid, haemoglobin and hormone tests usually identifies the reason within a single visit &mdash; which is why waiting a year for it to settle on its own rarely helps.</p>

      <h3>Symptoms that should not wait</h3>
      <ul class="dabg-list">
        <li><i class="fas fa-exclamation-circle"></i> Bleeding between periods, after intercourse, or any bleeding after menopause</li>
        <li><i class="fas fa-exclamation-circle"></i> Periods lasting more than seven days, or soaking through protection every one to two hours</li>
        <li><i class="fas fa-exclamation-circle"></i> Severe pelvic pain that stops you from working or attending school</li>
        <li><i class="fas fa-exclamation-circle"></i> Not conceiving after one year of trying &mdash; six months if you are over 35</li>
        <li><i class="fas fa-exclamation-circle"></i> A breast lump, or persistent foul-smelling discharge</li>
