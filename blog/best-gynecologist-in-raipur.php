<h2 id="first-visit">Preparing for Your First Visit</h2>
<ul>
    <li><strong>Write your dates down.</strong> Last period, cycle length, when symptoms started. Trying to recall this under pressure rarely works.</li>
    <li><strong>Bring everything.</strong> Old prescriptions, scan reports and the actual films, blood test results, your blood group card.</li>
    <li><strong>List your medicines.</strong> Including supplements and any ayurvedic or homeopathic preparations.</li>
    <li><strong>Note family history.</strong> Diabetes, high blood pressure, thyroid disease, cancers, sickle cell.</li>
    <li><strong>Come fasting</strong> if a blood sugar test is likely, and with a full bladder if an early pregnancy scan is planned.</li>
    <li><strong>Write your questions down</strong> and ask the most important one first.</li>
</ul>

<h2 id="second-opinion">When to Get a Second Opinion</h2>
<p>A second opinion is routine in medicine and costs one consultation fee. It is particularly worth getting when:</p>
<ul>
    <li>A hysterectomy is advised and you may still want children</li>
    <li>Open surgery is recommended without any discussion of a <a href="../blog/best-3d-laparoscopic-surgeon-in-chhattisgarh" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">keyhole alternative</a></li>
    <li>An elective caesarean is proposed with no clear medical reason given</li>
    <li>You are told an ovary must be removed for a cyst</li>
    <li>IVF is suggested before basic fertility tests have been completed</li>
    <li>The explanation does not make sense to you, or you feel rushed</li>
</ul>
<p>Take your reports and scan films with you. A good second opinion often confirms the first, which is itself useful: you proceed with confidence instead of doubt.</p>

