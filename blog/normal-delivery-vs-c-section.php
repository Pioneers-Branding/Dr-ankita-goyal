<h2 id="myths">Five Myths Worth Correcting</h2>
<ul>
    <li><strong>A caesarean is safer for the baby.</strong> For an uncomplicated pregnancy, normal delivery is safer for both. Caesarean is safer only when there is a specific reason for it.</li>
    <li><strong>A big baby on scan means a caesarean.</strong> Scan weight estimates carry a wide margin of error, and many women deliver larger babies normally.</li>
    <li><strong>Epidural leads to a caesarean.</strong> Current evidence does not support this. Epidural may lengthen pushing slightly but does not raise the caesarean rate.</li>
    <li><strong>Normal delivery after 35 is not possible.</strong> Age alone is not an indication for caesarean. Many women over 35 deliver normally.</li>
    <li><strong>A caesarean means no breastfeeding.</strong> Breastfeeding works perfectly well after a caesarean, sometimes starting a few hours later with help to find a comfortable position.</li>
</ul>

