<h2 id="the-difference">What Each One Actually Involves</h2>
<p><strong>Normal (vaginal) delivery</strong> happens in three stages. The cervix opens, which is the longest part and can take many hours in a first pregnancy. The baby is then pushed out, usually over minutes to a couple of hours. Finally the placenta is delivered. Pain relief options range from breathing and position changes to injections and epidural anaesthesia where available. A small cut called an episiotomy is sometimes made to prevent an uncontrolled tear.</p>
<p><strong>Caesarean section</strong> is an operation. A spinal anaesthetic numbs you from the chest down while you stay awake, which is the usual approach, and a horizontal cut is made low on the abdomen. The baby is delivered within minutes, and most of the operating time is spent closing the layers. General anaesthesia is reserved for emergencies where there is no time for a spinal.</p>
<p>A caesarean may be <strong>planned</strong>, decided in advance for a known reason, or <strong>emergency</strong>, decided during labour when something changes. An emergency caesarean is not a disaster: it means the team noticed a problem and acted. That is the system working.</p>

<h2 id="when-needed">When a Caesarean Is Genuinely Needed</h2>
<ul>
    <li><strong>Foetal distress:</strong> the baby's heart rate shows it is not coping with labour</li>
    <li><strong>Obstructed labour:</strong> labour stops progressing despite good contractions</li>
    <li><strong>Placenta praevia:</strong> the placenta covers the cervix, blocking the exit</li>
    <li><strong>Placental abruption:</strong> the placenta separates early, an emergency</li>
    <li><strong>Breech or transverse lie:</strong> the baby is bottom-down or lying sideways near term</li>
    <li><strong>Cord prolapse:</strong> the cord slips ahead of the baby, an immediate emergency</li>
    <li><strong>Severe preeclampsia or eclampsia</strong> where labour is not safe or fast enough</li>
    <li><strong>Certain previous uterine surgery</strong> such as a classical caesarean scar or extensive myomectomy</li>
    <li><strong>Twins in an unfavourable position</strong>, or triplets</li>
    <li><strong>Active genital herpes or untreated HIV</strong> with a high viral load</li>
</ul>
<p>Notice what is not on that list: maternal age alone, a first pregnancy alone, a slightly large baby on scan, or convenience of date. If a caesarean is proposed for a reason not on this list, asking for the clinical rationale in plain language is entirely reasonable.</p>

