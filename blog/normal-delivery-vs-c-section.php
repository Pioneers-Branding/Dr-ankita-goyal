<h2 id="faqs">Frequently Asked Questions</h2>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">1. Which is better, normal delivery or a C-section?</h3>
    <p>For an uncomplicated pregnancy, normal delivery is better: faster recovery, shorter stay, less blood loss, lower infection risk and lower cost. A caesarean is better only when there is a specific medical reason, in which case it is clearly the safer choice.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">2. How long does recovery take after each?</h3>
    <p>After a normal delivery, most women are discharged within 24 to 48 hours and feel largely recovered within two weeks. After a caesarean, the stay is three to five days and full recovery takes four to six weeks, with lifting restrictions in between.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">3. Is a C-section more expensive?</h3>
    <p>Yes, in private hospitals, because of theatre charges, anaesthesia, more medication and extra days of stay. Government facilities provide both free under national schemes. Ask for written estimates for both, since a normal delivery can become a caesarean.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">4. Can I have a normal delivery after a previous caesarean?</h3>
    <p>Often yes. VBAC is reasonable with one previous low transverse caesarean, a head-down baby, no new reason for surgery, and a hospital able to perform an emergency caesarean immediately. Raise it by around 32 weeks so a proper plan can be made.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">5. Does a big baby on scan mean I need a caesarean?</h3>
    <p>Not usually. Scan weight estimates have a wide margin of error, often several hundred grams, and many women deliver larger babies normally. The decision depends on labour progress, not the scan number alone.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">6. What can I do to increase my chance of normal delivery?</h3>
    <p>Attend every antenatal visit, correct anaemia early, keep weight gain steady, stay active, control blood sugar and blood pressure, check the baby's position after 36 weeks, and avoid induction before the body is ready.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">7. How soon can I breastfeed after a caesarean?</h3>
    <p>Usually within the first few hours. A spinal anaesthetic leaves you awake and alert. You may need help finding a position that avoids pressure on the wound, such as the side-lying or football hold.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">8. What should I check about the hospital before delivery?</h3>
    <p>Whether an emergency caesarean can be done at any hour, whether blood can be arranged quickly, whether newborn care is available on site, who will attend the delivery, and what the policy is on having a companion with you.</p>
</div>

