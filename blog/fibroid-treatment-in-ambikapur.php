<h2 id="what-are-fibroids">What Are Uterine Fibroids?</h2>
<p>Fibroids, medically called leiomyomas or myomas, are benign growths of the muscular wall of the uterus. They range from the size of a pea to larger than a melon, and a woman may have one or many. They are <strong>not cancer</strong>, and the risk of a fibroid turning malignant is extremely low, well under 1 in 1,000.</p>
<p>Their growth is driven by oestrogen and progesterone, which explains the pattern most women notice: fibroids tend to grow during the reproductive years, can enlarge during pregnancy, and usually shrink after menopause when hormone levels fall. Family history matters too, so if your mother or sister had fibroids, your own likelihood is higher.</p>
<p>By the age of 50, studies suggest up to 70 percent of women have had at least one fibroid. Most never know, because most fibroids cause no symptoms whatsoever.</p>

<h2 id="types">Types and Why Location Matters</h2>
<p>This is the part most patients are never told, and it matters more than size. A small fibroid in the wrong place causes far more trouble than a large one sitting quietly on the outer wall.</p>
