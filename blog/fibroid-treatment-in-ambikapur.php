<h2 id="faqs">Frequently Asked Questions</h2>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">1. Are uterine fibroids cancerous?</h3>
    <p>No. Fibroids are benign growths. The chance of a fibroid being a cancerous leiomyosarcoma is extremely low, under 1 in 1,000. Rapid growth, or any growth after menopause, does warrant prompt evaluation.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">2. Can fibroids be treated without surgery?</h3>
    <p>Yes, in many cases. Symptom-free fibroids need only monitoring. Heavy bleeding can often be controlled with medication or a hormonal intrauterine device. Surgery is reserved for significant symptoms, fertility problems or rapid growth.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">3. Will I lose my uterus?</h3>
    <p>Not necessarily. Myomectomy removes fibroids while preserving the uterus and is the preferred option for women who want children. Hysterectomy is considered only for completed families with severe or recurrent disease.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">4. Can I get pregnant after fibroid surgery?</h3>
    <p>Yes. Many women conceive after myomectomy, and removing a submucosal fibroid often improves fertility markedly. A gap of three to six months is generally advised before trying, to allow the uterine wall to heal fully.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">5. Do fibroids come back after removal?</h3>
    <p>New fibroids can develop after myomectomy, since the underlying tendency remains. Recurrence is more likely in younger women and where multiple fibroids were removed. Hysterectomy is the only option after which fibroids cannot return.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">6. How fast do fibroids grow?</h3>
    <p>Most grow slowly over years. Growth is faster during pregnancy and slows after menopause. Rapid enlargement over a few months should always be assessed rather than watched.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">7. Does diet shrink fibroids?</h3>
    <p>No diet removes an existing fibroid. However, maintaining a healthy weight, correcting anaemia with iron-rich food, and limiting alcohol supports overall management and reduces symptom severity. Be sceptical of products claiming to dissolve fibroids.</p>
</div>
