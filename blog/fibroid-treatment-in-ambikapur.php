<p>So when your report says "5 cm fibroid", the useful follow-up question is not just how big, but <em>where</em>. That single answer usually decides whether you need treatment.</p>

<h2 id="symptoms">Symptoms and Warning Signs</h2>
<p>Many fibroids are found by accident during a scan for something else. When they do cause symptoms, these are the common ones:</p>
<ul>
    <li><strong>Heavy or prolonged periods:</strong> soaking through protection every one to two hours, passing large clots, or bleeding beyond seven days.</li>
    <li><strong>Anaemia:</strong> fatigue, breathlessness climbing stairs, palpitations and pale skin. Often the first sign that bleeding has been heavier than you realised.</li>
    <li><strong>Pelvic pressure or heaviness:</strong> a persistent full feeling in the lower abdomen between periods.</li>
    <li><strong>Frequent urination:</strong> or difficulty emptying the bladder fully, from pressure on the bladder.</li>
    <li><strong>Constipation and bloating:</strong> when a fibroid presses on the rectum.</li>
    <li><strong>Lower back or leg pain:</strong> from pressure on nerves behind the uterus.</li>
    <li><strong>Pain during intercourse:</strong> depending on fibroid position.</li>
    <li><strong>Visibly enlarged abdomen:</strong> swelling not explained by weight gain.</li>
    <li><strong>Fertility difficulties:</strong> trouble conceiving or repeated early miscarriage, particularly with submucosal fibroids.</li>
</ul>
<p>Sudden, severe pelvic pain with fever or vomiting needs same-day assessment rather than a routine appointment. It can indicate a twisted or degenerating fibroid.</p>

