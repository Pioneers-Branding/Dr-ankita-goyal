<h2 id="faqs">Frequently Asked Questions</h2>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">1. What size ovarian cyst needs surgery?</h3>
    <p>There is no single number, but surgery is commonly considered above 5 to 6 cm, particularly if the cyst persists beyond two or three cycles or is growing. A simple cyst under 5 cm with no symptoms usually needs only a repeat scan.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">2. Do ovarian cysts go away on their own?</h3>
    <p>Functional cysts, which are the most common type, usually resolve within two or three menstrual cycles. Dermoid cysts, endometriotic cysts and cystadenomas do not resolve and need a decision about treatment.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">3. Are ovarian cysts cancerous?</h3>
    <p>The overwhelming majority are not, especially in women of reproductive age. Features that raise concern are solid areas on ultrasound, rapid growth, a cyst appearing after menopause, or fluid in the abdomen. These need prompt specialist assessment.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">4. Will I lose my ovary?</h3>
    <p>Usually not. Cystectomy removes the cyst and preserves the ovary, and this is the aim in almost all women of reproductive age. The whole ovary is removed only when it cannot be salvaged, such as after torsion with dead tissue.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">5. Can I get pregnant after ovarian cyst surgery?</h3>
    <p>Yes. Cystectomy preserves the ovary specifically for that reason. Even with one ovary removed, the other usually takes over and ovulates every month. Tell your surgeon before the operation if you are planning a pregnancy.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">6. What is a chocolate cyst?</h3>
    <p>An endometriotic cyst, formed when endometriosis deposits inside the ovary bleed each cycle and the old blood collects. It is called a chocolate cyst because of the thick brown fluid inside. It does not resolve on its own.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">7. Is a polycystic ovary the same as having ovarian cysts?</h3>
    <p>No. Polycystic ovaries show many small immature follicles, which are part of PCOS, a hormonal condition managed with lifestyle and medication. They are not cysts requiring removal, and surgery is not the treatment for PCOS.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">8. When is sudden pelvic pain an emergency?</h3>
    <p>Sudden severe one-sided pain, especially with nausea and vomiting, can mean ovarian torsion or a ruptured cyst with internal bleeding. Go to hospital immediately. Torsion can often be reversed and the ovary saved if treated within hours.</p>
</div>

