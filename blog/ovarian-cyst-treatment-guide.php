<h2 id="symptoms">Symptoms and Emergency Warning Signs</h2>
<p>Most cysts cause nothing at all and are found incidentally. When symptoms do occur:</p>
<ul>
    <li>A dull ache or heaviness on one side of the lower abdomen</li>
    <li>Bloating or a feeling of fullness</li>
    <li>Pain during intercourse, often on one side</li>
    <li>Pain around the middle of the cycle</li>
    <li>Changes in cycle pattern</li>
    <li>Needing to pass urine more often, from pressure on the bladder</li>
</ul>
<p><strong>Go to hospital immediately</strong> for sudden severe pain on one side, especially with nausea and vomiting. This can indicate ovarian torsion, where the ovary twists on its blood supply, or a ruptured cyst with internal bleeding. Torsion is a true emergency: the ovary can be saved if treated within hours, and is often lost if the delay runs into days.</p>

<h2 id="tests">How Cysts Are Assessed</h2>
<ul>
    <li><strong>Pelvic ultrasound:</strong> the main test, usually transvaginal for a clearer view. It describes size, whether the cyst is simple or complex, and whether there are solid areas inside.</li>
    <li><strong>Repeat ultrasound:</strong> after one to three months. This single step avoids a great deal of unnecessary surgery, since a functional cyst will simply have gone.</li>
    <li><strong>Pregnancy test:</strong> always, in women of reproductive age, as an ectopic pregnancy can look similar.</li>
    <li><strong>CA-125 and other markers:</strong> used selectively. CA-125 is often raised in endometriosis, fibroids and even during menstruation, so a mildly raised result in a young woman usually means very little.</li>
    <li><strong>MRI:</strong> for complex or large cysts where ultrasound is not conclusive.</li>
</ul>
<p>If surgery is being discussed, our guide on <a href="../blog/best-3d-laparoscopic-surgeon-in-raipur" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">choosing a laparoscopic surgeon</a> covers what to ask. The single most useful thing you can do is keep your old scan reports. A cyst that has been the same size for two years is a very different proposition from one that has doubled in six months.</p>

<h2 id="need-surgery">Which Cysts Need Surgery</h2>
<p>Surgery is generally considered when:</p>
<ul>
    <li>The cyst persists beyond two or three cycles instead of resolving</li>
    <li>It is larger than about 5 to 6 cm, particularly if it is growing</li>
    <li>It looks complex on ultrasound, with solid areas, thick walls or internal divisions</li>
    <li>It is a dermoid or an endometriotic cyst, neither of which resolves on its own</li>
    <li>It causes significant pain or pressure symptoms</li>
    <li>There has been torsion or rupture</li>
    <li>It appears after menopause</li>
    <li>It is interfering with fertility treatment</li>
</ul>
<p>Equally, surgery is usually <strong>not</strong> needed for a simple cyst under 5 cm with no symptoms, polycystic ovaries in PCOS, or a cyst that has not yet had a repeat scan. If an operation is proposed on a first scan showing a simple cyst, asking to repeat the scan in six to eight weeks first is entirely reasonable.</p>

<h2 id="surgery">What the Operation Involves</h2>
<p>The great majority of ovarian cyst operations are done laparoscopically, through three or four incisions of 5 to 10 mm.</p>
<p><strong>Cystectomy</strong> removes the cyst while leaving the healthy ovary behind. This is the aim in almost all women of reproductive age. The cyst wall is carefully peeled away from normal ovarian tissue, which is exactly the kind of delicate work where <a href="../blog/best-3d-laparoscopic-surgeon-in-chhattisgarh" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">3D depth perception</a> helps.</p>
<p><strong>Oophorectomy</strong> removes the whole ovary, and is reserved for situations where the ovary cannot be salvaged, such as torsion with dead tissue, or where cancer is suspected. Even then, a woman with one healthy ovary continues to ovulate, menstruate and can usually conceive.</p>
<p>Recovery follows the usual keyhole pattern: home within 24 to 48 hours, desk work at about two weeks, full activity at around six weeks. The cyst is always sent for histopathology, with results usually available in about a week.</p>

<h2 id="fertility">Cysts, Fertility and Your Ovary</h2>
<p>Two concerns come up constantly in consultations.</p>
<p><strong>Will surgery reduce my fertility?</strong> Removing the cyst while preserving the ovary has a small effect on ovarian reserve, because some normal tissue inevitably goes with the cyst wall. The effect is greatest with endometriotic cysts and with repeated operations on the same ovary. This is precisely why surgery should be done once, properly, by a surgeon who works carefully, rather than repeatedly.</p>
<p><strong>Can I conceive with one ovary?</strong> Yes. The remaining ovary takes over and typically ovulates every month rather than alternating. Fertility is reduced only modestly.</p>
<p>If you are planning a pregnancy, say so clearly before surgery. It changes the surgical approach and how much tissue is preserved.</p>

