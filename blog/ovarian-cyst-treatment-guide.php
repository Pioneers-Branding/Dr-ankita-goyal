<h2 id="what-they-are">What an Ovarian Cyst Actually Is</h2>
<p>A cyst is a fluid-filled sac. Every month the ovary grows a follicle, a small fluid-filled structure containing an egg, which ruptures at ovulation. That is a cyst by definition, and it is entirely normal.</p>
<p>Problems arise when the process does not complete. If the follicle does not rupture, it keeps growing as a follicular cyst. If it ruptures and then seals and fills with fluid, it becomes a corpus luteum cyst. Both are called functional cysts, both are harmless, and both almost always disappear within two or three cycles.</p>
<p>Because this is tied to ovulation, functional cysts are common in women of reproductive age and uncommon after menopause. A cyst found after menopause is therefore taken more seriously, not because it is likely to be cancer, but because the usual harmless explanation no longer applies.</p>

