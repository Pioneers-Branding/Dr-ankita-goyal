<h2 id="health-picture">Women's Health in Chhattisgarh: The Real Picture</h2>
<p>Three features shape gynaecological practice here more than anywhere else in India.</p>
<p><strong>Anaemia is the default, not the exception.</strong> National survey data puts more than half of pregnant women in India in the anaemic range, and Chhattisgarh sits close to that figure. A low haemoglobin is so common that it often gets noted and ignored. It should not be. It is the most preventable cause of a dangerous delivery, and correcting it takes time, which means it must be found early.</p>
<p><strong>Sickle cell is a genuine consideration.</strong> Chhattisgarh carries one of the highest burdens of the sickle cell gene in the country, which is why the state is a focus of the national Sickle Cell Anaemia Elimination Mission. For a pregnant woman this matters twice over: sickle cell disease makes a pregnancy high-risk, and if both parents carry the trait the baby can inherit the disease. Screening is a simple blood test.</p>
<p><strong>Distance changes clinical decisions.</strong> When a patient lives four hours from the hospital, you cannot plan care around frequent visits or assume she can return quickly if something goes wrong. That affects when iron is given intravenously rather than as tablets, when a patient is admitted earlier rather than sent home, and how firmly a delivery plan is made in advance.</p>

<h2 id="what-to-look">What to Look For in a Gynecologist</h2>
<ul>
    <li><strong>Postgraduate qualification.</strong> MS or MD in Obstetrics and Gynaecology. Any further fellowship, such as FMAS for minimal access surgery, adds specific surgical training.</li>
    <li><strong>Continuity of care.</strong> The same doctor at each visit, and ideally at the delivery.</li>
    <li><strong>Emergency capability at the hospital.</strong> Caesarean at any hour, blood arrangement, newborn care on site. Ask these three questions directly.</li>
    <li><strong>Routine screening.</strong> Haemoglobin, thyroid, blood sugar and sickle cell should be offered without you having to request them.</li>
    <li><strong>Uterus-preserving preference.</strong> Surgery that keeps the uterus where that is clinically reasonable.</li>
    <li><strong>Written costs.</strong> An estimate before admission, with exclusions stated.</li>
    <li><strong>Clear explanations.</strong> In the language you are comfortable in, with time for questions.</li>
</ul>

