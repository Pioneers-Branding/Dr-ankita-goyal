<h2 id="pregnancy">Pregnancy Care From Booking to Delivery</h2>
<p>The schedule that should be followed anywhere in the state:</p>
<ul>
    <li><strong>6 to 8 weeks:</strong> dating scan, blood group, haemoglobin, thyroid, blood sugar, infection screening, sickle cell test, baseline blood pressure and weight</li>
    <li><strong>11 to 13 weeks:</strong> NT scan and double marker test</li>
    <li><strong>18 to 20 weeks:</strong> anomaly scan, the detailed check of the baby's organs</li>
    <li><strong>24 to 28 weeks:</strong> glucose test for <a href="../blog/gestational-diabetes-during-pregnancy" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">gestational diabetes</a>, repeat haemoglobin, tetanus dose</li>
    <li><strong>28 to 36 weeks:</strong> growth scans, Doppler study where indicated, position check</li>
    <li><strong>37 weeks onwards:</strong> weekly review and delivery planning</li>
</ul>
<p>Blood pressure and urine protein are checked at every visit because <a href="../blog/high-blood-pressure-during-pregnancy" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">preeclampsia</a> develops quietly between appointments. The full visit-by-visit breakdown is in our <a href="../blog/pregnancy-checkup-schedule" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">pregnancy checkup schedule</a>.</p>
<p>On delivery, normal birth is preferred whenever it is safe. What genuinely improves the chances is regular antenatal visits, correcting anaemia early, controlled weight gain, staying active and monitoring the baby's position after 36 weeks. The <a href="../blog/normal-delivery-vs-c-section" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">comparison of normal delivery and caesarean</a> covers costs and recovery in detail.</p>

<h2 id="surgery">Surgical Options Now Available</h2>
<p>The most important change in the state over the last decade is that major gynaecological surgery no longer requires a long abdominal cut. Fibroid removal, hysterectomy, ovarian cyst removal and endometriosis surgery can all be done through incisions of 5 to 10 mm.</p>
<p>The practical difference is two weeks off work instead of six, 24 to 48 hours in hospital instead of a week, less blood loss and a lower infection risk. For a family depending on daily wages, that is not a cosmetic preference.</p>
<p>If you have been advised open surgery, it is reasonable to ask whether a keyhole approach is possible in your case. Sometimes the honest answer is no: a very large fibroid uterus, extensive adhesions or suspected cancer are genuine reasons for open surgery. But it should be a discussion, not an assumption. Our guide on <a href="../blog/best-3d-laparoscopic-surgeon-in-chhattisgarh" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">choosing a laparoscopic surgeon in Chhattisgarh</a> sets out the questions to ask.</p>

