<h2 id="what-it-is">What Endometriosis Is</h2>
<p>The lining of the uterus, the endometrium, builds up each month and sheds as a period. In endometriosis, tissue that behaves like that lining grows outside the uterus: on the ovaries, the fallopian tubes, the ligaments supporting the uterus, the bladder, the bowel, or the lining of the pelvis.</p>
<p>That tissue responds to the same hormones, so it thickens and bleeds every cycle. But there is nowhere for the blood to go. It stays in the pelvis, causing inflammation, and over time the body walls it off with scar tissue. Those adhesions stick organs together, which explains why the pain is often not limited to the period itself.</p>
<p>On the ovary it can form a cyst filled with old blood, called an endometrioma or chocolate cyst, covered in more detail in our guide on <a href="../blog/ovarian-cyst-treatment-guide" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">ovarian cysts</a>.</p>
<p>A related condition, adenomyosis, occurs when the same tissue grows into the muscular wall of the uterus itself, causing heavy bleeding and a constant dragging pain. The two often occur together.</p>

<h2 id="not-normal">When Period Pain Is Not Normal</h2>
<p>Mild cramping in the first day or two, relieved by a simple painkiller, is normal. These are not:</p>
<ul>
    <li>Pain that makes you miss school, work or normal activities</li>
    <li>Pain not controlled by standard over-the-counter painkillers</li>
    <li>Pain that starts days before the period and continues after it ends</li>
    <li>Pain that has been getting steadily worse over months or years</li>
    <li>Pain with vomiting or fainting</li>
    <li>Pelvic pain at other times of the month</li>
</ul>
<p>If a teenager is regularly missing school because of periods, that deserves investigation rather than reassurance. Early diagnosis changes the long-term course.</p>

