<h2 id="faqs">Frequently Asked Questions</h2>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">1. How do I know if my period pain is normal?</h3>
    <p>Mild cramping in the first day or two, relieved by a simple painkiller, is normal. Pain that makes you miss work or school, is not controlled by standard painkillers, starts days before the period, or is getting worse over time is not normal and should be assessed.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">2. Can endometriosis be seen on an ultrasound?</h3>
    <p>Only partly. Ultrasound detects chocolate cysts and adenomyosis well, but frequently misses superficial deposits. A normal ultrasound does not rule out endometriosis, which is why many women are wrongly reassured.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">3. Can endometriosis be cured?</h3>
    <p>There is no permanent cure, but it can be controlled effectively with pain management, hormonal treatment and surgery. Symptoms usually improve substantially with the right combination, and often settle after menopause.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">4. Does endometriosis cause infertility?</h3>
    <p>It can make conception harder through adhesions, tubal damage, reduced egg quality and inflammation, and it is found in a large share of women investigated for infertility. Many women with endometriosis still conceive naturally, and surgery improves the chances in mild to moderate disease.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">5. What is the difference between endometriosis and adenomyosis?</h3>
    <p>In endometriosis, the tissue grows outside the uterus, on the ovaries, ligaments, bowel or pelvic lining. In adenomyosis it grows into the muscular wall of the uterus itself, causing heavy bleeding and a constant dragging pain. The two often occur together.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">6. Will a hysterectomy cure my endometriosis?</h3>
    <p>Not necessarily. Deposits outside the uterus can persist and continue causing pain. Hysterectomy is considered only for severe disease, in a woman who has completed her family, after other treatments have failed.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">7. Should a teenager with severe period pain be investigated?</h3>
    <p>Yes. If a girl is regularly missing school because of period pain, or painkillers are not controlling it, she deserves assessment rather than reassurance. Early diagnosis and treatment change the long-term course of the disease.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">8. Is surgery the only option?</h3>
    <p>No. Many women are managed well with correctly timed anti-inflammatory medicine and hormonal treatment. Surgery is used when the diagnosis is unclear, medical treatment has failed, there is a large cyst, or fertility is affected.</p>
</div>

