<h2 id="faqs">Frequently Asked Questions</h2>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">1. What sugar level means gestational diabetes?</h3>
    <p>Under India's national guideline, a blood sugar of 140 mg/dL or more two hours after drinking 75 g of glucose confirms gestational diabetes. The test does not require fasting.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">2. When should the gestational diabetes test be done?</h3>
    <p>At the first antenatal visit, and again at 24 to 28 weeks if the first result was normal. If your first visit is after 28 weeks, a single test is done at that visit.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">3. Will gestational diabetes harm my baby?</h3>
    <p>When sugar is kept within target, most babies are born healthy. Poorly controlled sugar raises the risk of a large baby, low sugar after birth, breathing problems and, late in pregnancy, stillbirth. Good control reduces all of these sharply.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">4. Can I eat rice and roti with gestational diabetes?</h3>
    <p>Yes, in controlled portions. One or two rotis or a small katori of rice per meal, preferably multigrain, millet or brown rice, with plenty of vegetables and protein. Smaller, more frequent meals keep sugar steadier than large ones.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">5. Is insulin safe during pregnancy?</h3>
    <p>Yes. Insulin does not cross the placenta in meaningful amounts and can be used at any stage of pregnancy. It is started when diet and exercise have not brought sugar within target after about two weeks.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">6. Does gestational diabetes mean I need a caesarean?</h3>
    <p>No. Many women with well-controlled gestational diabetes have a normal delivery, often induced at or after 39 weeks. A caesarean is advised if the baby is very large or for the usual obstetric reasons.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">7. Does gestational diabetes go away after delivery?</h3>
    <p>In most women, yes. A repeat 75 g glucose test about six weeks after delivery confirms it. However, the lifetime risk of type 2 diabetes is much higher, so a yearly sugar test, a healthy weight and regular activity are important afterwards.</p>
</div>
