<p>Because the risk is high across Indian women, the national guideline does not wait for risk factors. Every pregnant woman is tested.</p>

<h2 id="testing">How and When You Are Tested</h2>
<p>India's national guideline uses a single-step test, often called the DIPSI test. It is simple and does not require you to come fasting:</p>
<div class="dabg-table">
<table>
    <thead><tr><th>Step</th><th>What Happens</th></tr></thead>
    <tbody>
        <tr><td>When</td><td>At your first antenatal visit, and again at 24 to 28 weeks if the first test was normal</td></tr>
        <tr><td>The drink</td><td>75 g of glucose dissolved in water, taken whether or not you have eaten</td></tr>
        <tr><td>The wait</td><td>Sit quietly for two hours; do not eat or walk around</td></tr>
        <tr><td>The test</td><td>A blood sugar reading exactly two hours after the drink</td></tr>
        <tr><td>Result</td><td>140 mg/dL or higher means gestational diabetes</td></tr>
    </tbody>
</table>
</div>
<p>The test is available free at government health centres under the national programme. Some private labs and hospitals use a longer fasting test with three blood samples, which uses slightly different cut-offs. Either is valid; what matters is that the test is done at the right time and not skipped.</p>

<h2 id="effects">What It Means for Mother and Baby</h2>
<p>When the mother's sugar is high, extra sugar crosses the placenta. The baby's pancreas responds by making more insulin, which acts as a growth hormone. That single chain of events explains most of the risks.</p>
<h3>For the baby</h3>
<ul>
    <li><strong>A large baby (macrosomia):</strong> which makes delivery harder and raises the chance of shoulder difficulty during birth.</li>
    <li><strong>Low blood sugar after birth:</strong> the baby's insulin stays high for a while after the mother's sugar supply stops, so the baby's sugar is checked in the first hours.</li>
    <li><strong>Breathing difficulty and jaundice:</strong> more common, especially if delivered early.</li>
    <li><strong>Stillbirth:</strong> the risk rises with poorly controlled sugar late in pregnancy, which is the main reason control and timing of delivery matter.</li>
    <li><strong>Later life:</strong> a higher chance of childhood obesity and type 2 diabetes.</li>
</ul>
<h3>For the mother</h3>
<ul>
    <li>Higher risk of <a href="../blog/high-blood-pressure-during-pregnancy.php" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">high blood pressure and preeclampsia</a></li>
    <li>Excess amniotic fluid, which can cause discomfort and early labour</li>
    <li>Higher chance of caesarean delivery or induced labour</li>
    <li>Urinary and vaginal infections</li>
    <li>A substantially higher lifetime risk of type 2 diabetes; up to half of women with GDM develop it within about ten years without preventive steps</li>
</ul>
<p>The encouraging part is that every one of these risks falls sharply when sugar is kept within target. Control is what changes the outcome.</p>

<h2 id="targets">Blood Sugar Targets and Home Monitoring</h2>
<div class="dabg-table">
<table>
    <thead><tr><th>Reading</th><th>Target in Pregnancy</th></tr></thead>
    <tbody>
        <tr><td>Fasting (on waking, before food or tea)</td><td>Below 95 mg/dL</td></tr>
        <tr><td>2 hours after the start of a meal</td><td>Below 120 mg/dL</td></tr>
    </tbody>
</table>
</div>
<p>You will usually be asked to check with a glucometer at home. A common starting pattern is a fasting reading plus a reading two hours after each main meal, a few days a week, adjusted as your doctor advises. Write every reading down with the time and what you ate. That record is what allows your treatment to be adjusted properly, and it quickly shows you which meals push your sugar up.</p>

<h2 id="diet">Diet That Works With an Indian Kitchen</h2>
<p>This is not about starving or cutting out rice and roti entirely. It is about the type, the amount and the timing of carbohydrate. The baby still needs steady energy, so crash dieting is harmful.</p>
<ul>
    <li><strong>Eat small meals often:</strong> three moderate meals and two or three small snacks, rather than two large meals. This keeps sugar steady.</li>
    <li><strong>Control the grain portion:</strong> one or two rotis or a small katori of rice per meal, not a full plate. Measure it for the first few weeks.</li>
    <li><strong>Choose slower grains:</strong> multigrain atta, ragi, jowar, bajra, kodo and kutki millets, brown or hand-pounded rice. They raise sugar more gently than white rice and maida.</li>
    <li><strong>Fill half the plate with vegetables:</strong> sabzi, salad and leafy greens slow down sugar absorption.</li>
    <li><strong>Add protein every time:</strong> dal, paneer, curd, chana, sprouts, eggs, fish or chicken.</li>
    <li><strong>Breakfast is the hardest meal:</strong> morning insulin resistance is highest. Poha, upma, bread or sweet tea on their own often cause the biggest spike. Try besan chilla, moong dal chilla, eggs or vegetable upma with curd.</li>
    <li><strong>Cut sweet drinks first:</strong> sugar in tea, packaged juice, cold drinks, sherbet. These are often the single biggest source.</li>
    <li><strong>Fruit, not juice:</strong> one portion at a time, such as a guava, apple, orange or pear. Limit mango, chikoo, banana and grapes.</li>
    <li><strong>Walk after meals:</strong> a 10 to 15 minute walk after each main meal lowers the after-meal reading noticeably.</li>
</ul>
<p>Festivals and family functions are where plans usually break. A small portion of mithai eaten straight after a protein-rich meal, followed by a walk, does far less harm than sweets eaten on an empty stomach.</p>

<h2 id="medication">When Insulin or Metformin Is Needed</h2>
<p>Most women reach their targets with diet and activity alone. Under India's national guideline, if after two weeks of diet and exercise the two-hour after-meal reading is still 120 mg/dL or above, medication is started.</p>
<ul>
    <li><strong>Insulin:</strong> safe for the baby because it does not cross the placenta in meaningful amounts, and it can be used at any stage of pregnancy. The dose is adjusted to your readings, and modern insulin pens make injections small and nearly painless.</li>
    <li><strong>Metformin:</strong> a tablet that may be used after 20 weeks in suitable women. Some women on metformin still need insulin added.</li>
</ul>
<p>Needing medication is not a failure. It usually reflects placental hormones that are stronger than any diet can counter, and it is the safest way to protect the baby when diet alone is not enough.</p>

<h2 id="delivery">Delivery and After the Baby Is Born</h2>
<p>Gestational diabetes alone is not a reason for a caesarean. When sugar is well controlled and the baby is growing normally, delivery is not recommended before 39 weeks, and labour may be induced at or after 39 weeks. Earlier delivery is considered when sugar is poorly controlled or there are other complications. Growth scans in the third trimester help plan the timing and the mode of delivery.</p>
<p>After birth:</p>
<ul>
    <li>Your baby's sugar will be checked in the first hours; early and frequent breastfeeding helps keep it stable</li>
    <li>Insulin or metformin is usually stopped straight after delivery</li>
    <li>A repeat 75 g glucose test is done about six weeks after delivery to confirm your sugar has returned to normal</li>
    <li>After that, a sugar test every year, and before any future pregnancy</li>
    <li>Breastfeeding, returning to a healthy weight and staying active all lower your future diabetes risk</li>
</ul>

