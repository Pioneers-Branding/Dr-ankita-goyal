<h2 id="what-is-gdm">What Is Gestational Diabetes?</h2>
<p>During pregnancy, the placenta produces hormones that help the baby grow. As a side effect, these hormones make the mother's body less responsive to insulin, the hormone that moves sugar from the blood into cells. Most women's bodies simply make more insulin to compensate. When the body cannot keep up, blood sugar rises, and that is gestational diabetes (GDM).</p>
<p>It usually appears after 20 weeks, as placental hormones increase, and is most often found at the 24 to 28 week test. It is common in India: studies across the country report it in roughly one in ten pregnancies, and South Asian women are at higher risk than many other populations even at a normal weight.</p>
<p>It is different from type 1 or type 2 diabetes that existed before pregnancy. If very high sugar is found early in pregnancy, it may be pre-existing diabetes that was never diagnosed, and it is managed more intensively.</p>

