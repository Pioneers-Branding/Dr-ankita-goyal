<p>Two things are worth knowing. Having a risk factor does not mean you will have a complication. And you can have none of these and still develop one. Preeclampsia and gestational diabetes regularly appear in women with no risk factors at all, which is why routine visits matter even when you feel perfectly well.</p>

<h2 id="warning-signs">10 Warning Signs You Should Never Ignore</h2>
<p>These symptoms call for a phone call to your doctor the same day, not at your next scheduled visit.</p>
<ul>
    <li><strong>Vaginal bleeding at any stage.</strong> Light spotting early on is often harmless, but bleeding after 20 weeks can point to a placental problem. Heavy bleeding with pain is an emergency.</li>
    <li><strong>A severe or persistent headache.</strong> Especially one that does not ease with rest or paracetamol, or comes with blurred vision, flashing lights or spots. This combination is a classic sign of preeclampsia.</li>
    <li><strong>Sudden swelling of the face, hands or feet.</strong> Mild ankle swelling late in pregnancy is normal. Swelling that appears quickly, puffs up your face or makes rings tight is not.</li>
    <li><strong>Reduced or absent baby movements.</strong> The single most useful thing you can monitor yourself, covered in the next section.</li>
    <li><strong>Fluid leaking from the vagina before 37 weeks.</strong> A gush or a steady trickle may mean the waters have broken early, which carries an infection risk for the baby.</li>
    <li><strong>Severe or constant abdominal pain.</strong> Different from the stretching ache of a growing bump. Constant pain, or a hard and tender abdomen, needs immediate assessment.</li>
    <li><strong>Regular contractions before 37 weeks.</strong> Tightening that comes at regular intervals and grows stronger may be preterm labour, which can often be delayed if you reach hospital early.</li>
    <li><strong>Vomiting that will not stop.</strong> Particularly if you cannot keep fluids down for a day or are passing very little urine.</li>
    <li><strong>Fever above 100.4&deg;F (38&deg;C).</strong> With or without chills. Infection in pregnancy needs prompt, proper treatment rather than self-medication.</li>
    <li><strong>Burning when passing urine.</strong> Urinary infections are common in pregnancy and can trigger early labour if left untreated.</li>
</ul>

<h2 id="fetal-movement">Reduced Baby Movement: How to Check</h2>
<p>Ask an obstetrician which single habit protects the most babies and many will say movement counting. Yet it is the sign women most often talk themselves out of acting on.</p>
<p>Movements are usually first felt between 18 and 24 weeks, a little earlier in a second pregnancy. From around 28 weeks a pattern settles in, and what matters is your baby's pattern, not a textbook number.</p>
<div class="dabg-table">
<table>
    <thead><tr><th>Step</th><th>What to Do</th></tr></thead>
    <tbody>
        <tr><td>Pick a time</td><td>Choose a time your baby is usually active, often after a meal or in the evening</td></tr>
        <tr><td>Lie on your left side</td><td>This improves blood flow to the baby and makes movements easier to feel</td></tr>
        <tr><td>Count</td><td>Note how long it takes to feel 10 separate movements: kicks, rolls, flutters and jabs all count</td></tr>
        <tr><td>Reassuring</td><td>10 movements within 2 hours</td></tr>
        <tr><td>Act on it</td><td>Fewer than 10 in 2 hours, or a clear drop from your usual pattern, means you should be checked the same day</td></tr>
    </tbody>
</table>
</div>
<p>Two common beliefs are worth correcting. Babies do not run out of room and go quiet near term, so reduced movement at 38 weeks matters just as much as at 30. And drinking cold water or something sweet to make the baby kick is not a reliable test. If movements have genuinely slowed, get a proper check instead.</p>

<h2 id="monitoring">How a High-Risk Pregnancy Is Monitored</h2>
<p>There is no single fixed protocol. Monitoring is built around the risk you actually have, but a typical schedule looks like this:</p>
<div class="dabg-table">
<table>
    <thead><tr><th>Stage</th><th>What Is Checked</th></tr></thead>
    <tbody>
        <tr><td>6 to 8 weeks</td><td>Dating scan, blood group, haemoglobin, thyroid, blood sugar, infection screening, sickle cell screening, baseline blood pressure and weight</td></tr>
        <tr><td>11 to 13 weeks</td><td>NT scan and double marker test; low-dose aspirin may be advised if preeclampsia risk is high</td></tr>
        <tr><td>18 to 20 weeks</td><td>Anomaly scan, a detailed check of the baby's organs</td></tr>
        <tr><td>24 to 28 weeks</td><td>Glucose tolerance test, repeat haemoglobin, growth assessment</td></tr>
        <tr><td>28 to 36 weeks</td><td>Growth scans every 2 to 4 weeks, Doppler study of blood flow, amniotic fluid measurement</td></tr>
        <tr><td>36 weeks onwards</td><td>Weekly review, baby's position, non-stress test where needed, delivery planning</td></tr>
    </tbody>
</table>
</div>
<p>Blood pressure and urine protein are checked at every visit because preeclampsia can develop between appointments without any symptoms. Weight is tracked for a similar reason: a sudden jump can be fluid retention rather than healthy growth.</p>

<h2 id="when-to-go">When to Go to Hospital Immediately</h2>
<p>Do not wait for morning, do not wait for your next appointment, and do not ask on a family WhatsApp group first. Go straight to hospital if you have:</p>
<ul>
    <li>Heavy vaginal bleeding, with or without pain</li>
    <li>No baby movement at all for several hours</li>
    <li>A severe headache with blurred vision or flashing lights</li>
    <li>A fit, seizure or fainting episode</li>
    <li>Severe constant abdominal pain, or a hard and tender abdomen</li>
    <li>A sudden gush of fluid before 37 weeks</li>
    <li>Breathlessness or chest pain</li>
    <li>High fever with shivering</li>
</ul>
<p>If you are unsure whether a symptom counts, phone and describe it. A good obstetric team never minds a call about something that turns out to be nothing. What they do mind is being called twelve hours too late.</p>

