<h2 id="what-is-high-risk">What Makes a Pregnancy High-Risk?</h2>
<p>A high-risk pregnancy is one where the mother, the baby, or both have a higher than usual chance of a complication. Many women hear the label as a prediction that something will go wrong. It is not. It is a decision about how closely you should be watched.</p>
<p>In practice, it usually means more antenatal visits, more scans and a few extra blood tests. Most high-risk pregnancies end with a healthy mother and a healthy baby, largely because the extra checks catch problems while they are still small and manageable.</p>
<p>The label can be given at three points: at the booking visit, based on your age and medical history; during pregnancy, when a condition such as <a href="../blog/high-blood-pressure-during-pregnancy.php" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">high blood pressure</a> or <a href="../blog/gestational-diabetes-during-pregnancy.php" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">gestational diabetes</a> develops; or late in pregnancy, if the baby's growth slows or the placenta lies low.</p>

