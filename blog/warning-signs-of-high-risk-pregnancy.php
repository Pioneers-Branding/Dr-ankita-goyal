<h2 id="faqs">Frequently Asked Questions</h2>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">1. What are the first warning signs of a high-risk pregnancy?</h3>
    <p>The most important early signs are vaginal bleeding, a severe headache with blurred vision, sudden swelling of the face and hands, reduced baby movements and severe abdominal pain. Any of these needs a same-day call to your doctor rather than waiting for the next appointment.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">2. Does high-risk mean my baby is in danger?</h3>
    <p>No. High-risk means you need closer monitoring, not that something will go wrong. Most high-risk pregnancies end with a healthy mother and baby, because the extra scans and tests pick up problems early enough to manage them.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">3. How do I count my baby's movements?</h3>
    <p>Lie on your left side at a time your baby is usually active and count until you feel 10 separate movements. Ten within two hours is reassuring. Fewer than that, or a clear drop from your normal pattern, means you should be checked the same day.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">4. How often will I see my doctor in a high-risk pregnancy?</h3>
    <p>Usually monthly until 28 weeks, every two weeks until 36 weeks and weekly after that, with extra visits depending on your condition. Growth scans every two to four weeks are common in the third trimester.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">5. Can I still have a normal delivery?</h3>
    <p>Often, yes. Being high-risk changes how closely labour is monitored; it does not automatically mean a caesarean. The decision depends on your specific condition, the baby's growth and position, and how labour progresses.</p>
</div>
