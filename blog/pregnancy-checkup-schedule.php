<h2 id="first-tri">First Trimester: Up to 13 Weeks</h2>
<ul>
    <li><strong>Folic acid</strong> 400 micrograms daily, ideally started before conception and continued to 12 weeks, to reduce the risk of neural tube defects</li>
    <li><strong>NT scan at 11 to 13 weeks</strong> measuring fluid at the back of the baby's neck, combined with a blood test called the double marker, to assess the chance of chromosomal conditions</li>
    <li><strong>NIPT</strong> is an optional blood test from 10 weeks offering a more accurate screen; it is a screening test, not a diagnosis</li>
