<h2 id="scans">The Four Scans That Matter</h2>
<ul>
    <li><strong>Dating scan, 6 to 8 weeks.</strong> Confirms location and heartbeat, sets the due date. Come with a full bladder for an abdominal scan.</li>
    <li><strong>NT scan, 11 to 13 weeks.</strong> Screens for chromosomal conditions. The window is strict, so book it in advance.</li>
    <li><strong>Anomaly scan, 18 to 20 weeks.</strong> The most detailed scan of the pregnancy, checking organ development and placental position. Allow extra time; the baby's position may require you to walk around and return.</li>
    <li><strong>Growth scans, 28 weeks onwards.</strong> Track the baby's size, fluid and blood flow. Repeated every two to four weeks in a <a href="../blog/warning-signs-of-high-risk-pregnancy" style="color:#ee7c31; font-weight: 600; text-decoration: underline;">high-risk pregnancy</a>.</li>
</ul>
<p>Under Indian law, no scan will reveal the baby's sex. The PCPNDT Act prohibits sex determination, and every ultrasound centre displays this. It is not your doctor being unhelpful.</p>

