<h2 id="faqs">Frequently Asked Questions</h2>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">1. When should I have my first pregnancy scan?</h3>
    <p>Between 6 and 8 weeks. It confirms the pregnancy is inside the uterus, checks the heartbeat and sets your due date. A positive test with pain or bleeding needs a scan straight away rather than waiting.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">2. How many scans are needed in pregnancy?</h3>
    <p>Four are standard: dating at 6 to 8 weeks, NT at 11 to 13 weeks, anomaly at 18 to 20 weeks, and growth scans from 28 weeks. A high-risk pregnancy needs growth scans every two to four weeks in the third trimester.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">3. How often should I see my doctor?</h3>
    <p>Monthly until 28 weeks, every two weeks until 36 weeks, then weekly until delivery. High-risk pregnancies need more frequent visits, and beyond 40 weeks monitoring usually moves to twice weekly.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">4. What is the anomaly scan and why does it matter?</h3>
    <p>Done at 18 to 20 weeks, it is the detailed structural check of the baby's brain, heart, spine, kidneys and limbs, and it confirms the placenta's position. It is the most thorough scan of the pregnancy.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">5. When is the sugar test done in pregnancy?</h3>
    <p>At the first antenatal visit and again at 24 to 28 weeks if the first result was normal. The test uses 75 g of glucose and does not require fasting. A reading of 140 mg/dL or more after two hours confirms gestational diabetes.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">6. Why can the scan not tell me the baby's sex?</h3>
    <p>Sex determination is prohibited in India under the PCPNDT Act, and no ultrasound centre or doctor may disclose it. This applies everywhere in the country regardless of who performs the scan.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">7. When should I start counting baby movements?</h3>
    <p>From about 28 weeks. Lie on your left side at a time your baby is usually active and count to ten distinct movements. Ten within two hours is reassuring; a clear drop from your pattern needs same-day assessment.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">8. What should I carry to every antenatal visit?</h3>
    <p>One file with all previous reports, scan films and prescriptions, your blood group card, a list of medicines and supplements, and written questions. Come fasting if a sugar test is due and with a full bladder for an early scan.</p>
</div>

