    <li><strong>Anomaly scan at 18 to 20 weeks</strong>, the detailed structural check of the baby's brain, heart, spine, kidneys and limbs, and the position of the placenta</li>
    <li><strong>First movements</strong> felt between 18 and 24 weeks, earlier in a second pregnancy</li>
