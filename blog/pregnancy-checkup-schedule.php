<h2 id="warning">Warning Signs at Every Stage</h2>
<p>Contact your doctor the same day for any of these, at any point in pregnancy:</p>
<ul>
    <li>Vaginal bleeding</li>
    <li>Severe or persistent headache, especially with blurred vision or flashing lights</li>
    <li>Sudden swelling of the face, hands or feet</li>
    <li>Reduced or absent baby movements after 28 weeks</li>
    <li>Fluid leaking before 37 weeks</li>
    <li>Severe or constant abdominal pain</li>
    <li>Regular contractions before 37 weeks</li>
    <li>Fever above 100.4 degrees Fahrenheit</li>
    <li>Burning during urination or passing very little urine</li>
    <li>Persistent vomiting with inability to keep fluids down</li>
</ul>

