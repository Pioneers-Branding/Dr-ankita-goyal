    <li><strong>Nausea and vomiting</strong> peak around weeks 8 to 10 and usually settle by 14 weeks. Report inability to keep fluids down</li>
</ul>

<h2 id="second-tri">Second Trimester: 14 to 27 Weeks</h2>
<p>Usually the most comfortable stretch. Visits are monthly.</p>
