<h2 id="technology">The Technology Behind the Procedure</h2>
<p>The 3D Rubina laser system at Sankalp Hospital combines three things that each change what the surgeon can see.</p>
<p><strong>Depth perception.</strong> Two lenses feed each eye a separate image through polarised glasses, reproducing normal binocular vision. On a flat 2D screen, judging how far a needle is from a blood vessel depends on inference. In 3D, it is simply visible.</p>
<p><strong>4K resolution.</strong> Four times the detail of standard high definition, which matters when the task is separating a fibroid from healthy muscle along the correct plane.</p>
<p><strong>Fluorescence imaging.</strong> A dye is injected and viewed under a specific wavelength of light, showing blood supply live. The surgeon can confirm that tissue is perfused before deciding what to preserve, and identify structures such as the ureter with more confidence.</p>
<p>Equipment does not make a surgeon. It does widen what a well-trained surgeon can safely attempt without opening the abdomen.</p>

