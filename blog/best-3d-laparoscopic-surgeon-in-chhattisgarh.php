<h2 id="judge-a-surgeon">How to Judge a Laparoscopic Surgeon</h2>
<p>Every hospital website claims advanced laparoscopic facilities. These are the distinctions that matter:</p>
<ul>
    <li><strong>Formal fellowship training.</strong> FMAS is a recognised minimal access surgery qualification. A surgeon with MS or MD alone may have learned laparoscopy informally, which varies enormously in depth.</li>
    <li><strong>Case volume in your operation.</strong> Laparoscopic suturing is a skill that decays without practice. Ask how often the surgeon performs your specific procedure.</li>
    <li><strong>Honesty about conversion.</strong> Every laparoscopic surgeon occasionally converts to open surgery for safety. A surgeon who claims never to convert is either inexperienced or not being straight with you.</li>
    <li><strong>Uterus-preserving preference.</strong> If you may want children, the surgeon should be arguing to keep the uterus, not the other way round.</li>
    <li><strong>Continuity.</strong> The person who consults you should be the person who operates.</li>
    <li><strong>Written costs.</strong> A full estimate before admission, including what happens if the surgery takes longer than planned.</li>
</ul>

