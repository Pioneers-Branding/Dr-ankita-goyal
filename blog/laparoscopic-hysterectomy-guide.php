<h2 id="faqs">Frequently Asked Questions</h2>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">1. How long does recovery take after a laparoscopic hysterectomy?</h3>
    <p>Most women go home in 24 to 48 hours, return to desk work at about two weeks and are cleared for full activity including intercourse and exercise at six weeks. Open surgery typically needs six to eight weeks.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">2. Will I go into menopause after a hysterectomy?</h3>
    <p>Only if your ovaries are removed. If the ovaries are kept, they continue producing hormones and natural menopause arrives at the usual age. Periods stop either way, because the uterus is gone.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">3. Should my ovaries be removed at the same time?</h3>
    <p>Usually not if you are under about 45 and the ovaries are healthy, because early surgical menopause carries real costs for bone and heart health. Removal is advised for ovarian disease, severe endometriosis or a high genetic cancer risk.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">4. Can a hysterectomy be avoided for fibroids?</h3>
    <p>Often, yes. Medication, a hormonal intrauterine device, endometrial ablation, myomectomy and hysteroscopic removal all preserve the uterus. Fibroids without symptoms frequently need no treatment at all and shrink after menopause.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">5. Will intercourse be affected?</h3>
    <p>Usually not after six weeks of healing. The vagina is unchanged in length for most women. Some report improvement once heavy bleeding and pain have resolved. Dryness is more likely if the ovaries were removed.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">6. Do I still need Pap smears afterwards?</h3>
    <p>If the cervix was removed and the surgery was for a benign condition, routine Pap smears are generally not required. If the cervix was left in place, or the surgery was for cancer, screening continues. Confirm which operation you had.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">7. How much bleeding is normal after the operation?</h3>
    <p>Light vaginal bleeding or brownish discharge for up to six weeks is expected as internal stitches dissolve. Sudden heavy bleeding, fever or foul-smelling discharge needs prompt medical attention.</p>
</div>
<div style="margin-bottom: 20px;">
    <h3 style="color: #0A2F5C; font-size: 1.15rem;">8. Why do I have shoulder pain after keyhole surgery?</h3>
    <p>Carbon dioxide gas used to inflate the abdomen irritates the diaphragm, which shares a nerve supply with the shoulder. It is harmless, settles within a few days, and gentle walking helps the gas clear faster.</p>
</div>

