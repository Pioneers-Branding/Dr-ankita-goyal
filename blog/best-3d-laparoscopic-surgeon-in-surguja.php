<h2 id="judge">How to Judge a Surgeon</h2>
<p>Every hospital advertises advanced laparoscopic facilities. Owning a laparoscope is not the same as being trained to use it well. These are the distinctions that matter:</p>
<ul>
    <li><strong>Formal fellowship training.</strong> FMAS, the Fellowship in Minimal Access Surgery, is a recognised qualification taken after a postgraduate degree. A surgeon with MS or MD alone may have learned laparoscopy informally, and that varies enormously in depth.</li>
    <li><strong>Volume in your specific operation.</strong> Laparoscopic suturing is a skill that decays without regular practice. Asking how often the surgeon performs your particular procedure is a fair question.</li>
    <li><strong>Honesty about conversion.</strong> Every laparoscopic surgeon occasionally converts to open surgery for safety. One who claims never to convert is either inexperienced or not being straight with you.</li>
    <li><strong>A preference for preserving the uterus</strong> where that is clinically reasonable, especially if you may want children.</li>
    <li><strong>Continuity.</strong> The person who consults you should be the person who operates.</li>
    <li><strong>Written costs</strong> before admission, including what happens if the surgery takes longer than planned.</li>
</ul>

